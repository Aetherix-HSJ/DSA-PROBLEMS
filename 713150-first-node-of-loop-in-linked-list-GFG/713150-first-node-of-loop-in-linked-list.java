class Solution {
    public int cycleStart(Node head) {
        // code here
        Node slow = head;
        Node fast = head;
        while(fast!=null && fast.next!=null){
            slow = slow.next;
            fast = fast.next.next;
            if(slow==fast) break;
        }
        if(slow!=fast) return -1;
        Node b = head;
        while(b!=slow){
            b = b.next;
            slow = slow.next;
        }
        if(b==slow) return slow.data;
        return -1;
    }
}

